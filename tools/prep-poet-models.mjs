/* Prepares the character sculpts for Save the Poet.
   Reads assets/models/poet/<name>.glb (named for the character: archias,
   cicero, grattius, quintus, ...), welds and reduces each to a size a school
   laptop can draw, and writes the geometry into src/poet/models.gen.js, so the
   game stays one offline file. src/poet/sculpt.js colours and animates them;
   a character with no sculpt keeps its hand-built figure.
   Usage: node prep-poet-models.mjs */
import fs from 'fs';
import path from 'path';
import { NodeIO } from '@gltf-transform/core';
import { weld, simplify, dedup, prune } from '@gltf-transform/functions';
import { MeshoptSimplifier } from 'meshoptimizer';

const DIR = '../assets/models/poet', OUT = '../src/poet/models.gen.js';
/* triangles to keep: the faces the camera comes close to get the most */
const TARGET = { cicero: 14000, archias: 14000, cicero_crowd: 900, archias_crowd: 900, grattius: 10000, quintus: 10000, lucullus: 8000, juror: 5000, envoy: 5000 };
const io = new NodeIO();
await MeshoptSimplifier.ready;
const M = {};
/* each sculpt, and for the two the crowd is drawn from, a much lighter copy */
const jobs = fs.readdirSync(DIR).filter(f => f.endsWith('.glb')).flatMap(f => { const n = f.replace('.glb', '').toLowerCase(); return [[f, n], ...(TARGET[n + '_crowd'] ? [[f, n + '_crowd']] : [])]; });
for (const [f, name] of jobs) {
  if (!TARGET[name]) { console.log('skipping ' + f + ' (name it after a character: ' + Object.keys(TARGET).join(', ') + ')'); continue; }
  const doc = await io.read(path.join(DIR, f));
  await doc.transform(weld(), dedup());
  const prim0 = doc.getRoot().listMeshes()[0].listPrimitives()[0];
  const before = prim0.getIndices().getCount() / 3;
  await doc.transform(simplify({ simplifier: MeshoptSimplifier, ratio: Math.min(1, TARGET[name] / before), error: 0.004, lockBorder: false }), prune());
  const prim = doc.getRoot().listMeshes()[0].listPrimitives()[0];
  const idx = Array.from(prim.getIndices().getArray());
  const b64 = a => Buffer.from(a.buffer, a.byteOffset, a.byteLength).toString('base64');
  const wide = idx.some(v => v > 65535);
  M[name] = { pos: b64(new Float32Array(prim.getAttribute('POSITION').getArray())), idx: b64(wide ? new Uint32Array(idx) : new Uint16Array(idx)), wide };
  console.log(name.padEnd(9) + String(before).padStart(8) + ' tris -> ' + String(idx.length / 3).padStart(6) + '  (' + ((M[name].pos.length + M[name].idx.length) / 1024).toFixed(0) + ' KB in the page)');
}
fs.writeFileSync(OUT, '/* generated by tools/prep-poet-models.mjs from assets/models/poet - do not edit */\nexport const MODELS = ' + JSON.stringify(M) + ';\n');
console.log('wrote ' + OUT);
